def title_for(ids, fallback="PowerManagerII"):
    if MAIN_SIGNATURE <= frozenset(ids):
        return "PowerManagerII"
    template = match_template(ids)
    return TITLES.get(template["key"], template.get("title") or fallback) if template else fallback


def match_template(ids):
    ids = frozenset(ids) - {0, -1, 65535, 4294967295}
    return _match_template(ids)


@lru_cache(maxsize=128)
def _match_template(ids):
    ranked = []
    for template in TEMPLATES:
        expected = frozenset(template["ids"])
        score = len(ids & expected) / len(ids | expected) if ids | expected else 0
        ranked.append((score, template))
    ranked.sort(key=lambda pair: pair[0], reverse=True)
    if not ranked or ranked[0][0] < 0.80:
        return None
    if len(ranked) > 1 and ranked[0][0] - ranked[1][0] < 0.08:
        # Both vendor DLLs contain the same delete dialog. Their semantics are identical.
        equivalent = {"PMConfig.dll_5_143_1033", "PowerManager.exe_5_143_1033"}
        if {ranked[0][1]["key"], ranked[1][1]["key"]} != equivalent:
            return None
    return ranked[0][1]


def label_for(ids, cid, cls, existing=""):
    if MAIN_SIGNATURE <= frozenset(ids):
        if cls == "Button":
            return MAIN_BUTTONS.get(cid, existing)
        if cls == "SysListView32":
            return {1001: "Текущие события", 1034: "Таблица параметров ИБП"}.get(cid, existing)
        for value_id, name, _ in METRICS:
            if cid == value_id:
                return f"{name}: {existing.strip()}"
        return existing
    template = match_template(ids)
    if not template:
        return existing
    overrides = OVERRIDES.get(template["key"], {})
    if cid in overrides:
        return overrides[cid]
    if cls == "Button" and cid in (1, 2):
        return {1: "ОК", 2: "Отмена"}[cid]
    if cls == "Button" and not existing.strip():
        return template["labels"].get(str(cid), existing)
    return existing
